type Volume struct {
	Name string `yaml:"name"`
	Path string `yaml:"path"`
}
type Step struct {
	Name           string   `yaml:"name"`
	ID             string   `yaml:"id"`
	Entrypoint     string   `yaml:"entrypoint"`
	Dir            string   `yaml:"dir"`
	Args           []string `yaml:"args"`
	Env            []string `yaml:"env"`
	Script         string   `yaml:"script"`
	WaitFor        []string `yaml:"waitFor"`
	Volumes        []Volume `yaml:"volumes"`
	Timeout        string   `yaml:"timeout"`
	AllowFailure   bool     `yaml:"allowFailure"`
	AllowExitCodes []int    `yaml:"allowExitCodes"`
	Automap        *bool    `yaml:"automapSubstitutions"`
}
type Options struct {
	Env                []string `yaml:"env"`
	Volumes            []Volume `yaml:"volumes"`
	SubstitutionOption string   `yaml:"substitutionOption"`
	Automap            bool     `yaml:"automapSubstitutions"`
	MachineType        string   `yaml:"machineType"`
	DiskSizeGb         string   `yaml:"diskSizeGb"`
	Logging            string   `yaml:"logging"`
	LogStreamingOption string   `yaml:"logStreamingOption"`
}
type Config struct {
	Steps         []Step            `yaml:"steps"`
	Images        []string          `yaml:"images"`
	Substitutions map[string]string `yaml:"substitutions"`
	Timeout       string            `yaml:"timeout"`
	Options       Options           `yaml:"options"`
	Tags          []string          `yaml:"tags"`
}
type Plan struct {
	Source    string        `json:"source"`
	Workspace string        `json:"workspace"`
	Steps     []StepPlan    `json:"steps"`
	Images    []string      `json:"images"`
	Timeout   time.Duration `json:"timeout"`
}
type StepPlan struct {
	Step    Step          `json:"step"`
	Image   string        `json:"image"`
	Workdir string        `json:"workdir"`
	Env     []string      `json:"env"`
	Timeout time.Duration `json:"timeout"`
}

var userKey = regexp.MustCompile(`^_[A-Z0-9_]+$`)
var token = regexp.MustCompile(`\$\$|\$\{([A-Za-z_][A-Za-z0-9_]*)\}|\$([A-Za-z_][A-Za-z0-9_]*)`)

func load(filename string) (Config, error) {
	f, err := os.Open(filename)
	if err != nil {
		return Config{}, err
	}
	defer f.Close()
	dec := yaml.NewDecoder(f)
	dec.KnownFields(true)
	var c Config
	if err := dec.Decode(&c); err != nil {
		return c, fmt.Errorf("config: %w (unsupported Cloud Build features must be removed explicitly)", err)
	}
	var extra any
	if err := dec.Decode(&extra); err != io.EOF {
		return c, fmt.Errorf("config must contain exactly one YAML document")
	}
	if len(c.Steps) == 0 {
		return c, fmt.Errorf("config has no steps")
	}
	return c, nil
}

func substitute(s string, values map[string]string, loose bool) (string, error) {
	var err error
	result := token.ReplaceAllStringFunc(s, func(t string) string {
		if t == "$$" {
			return "$"
		}
		key := strings.TrimSuffix(strings.TrimPrefix(t, "${"), "}")
		if !strings.HasPrefix(t, "${") {
			key = t[1:]
		}
		if v, ok := values[key]; ok {
			return v
		}
		if loose && userKey.MatchString(key) {
			return t
		}
		err = fmt.Errorf("unknown substitution %s; shell variables must use $$", t)
		return t
	})
	return result, err
}

func duration(s string, fallback time.Duration) (time.Duration, error) {
	if s == "" {
		return fallback, nil
	}
	d, err := time.ParseDuration(s)
	if err != nil || d <= 0 {
		return 0, fmt.Errorf("invalid timeout %q", s)
	}
	return d, nil
}
func inside(root, file string) bool {
	rel, err := filepath.Rel(root, file)
	return err == nil && rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator))
}
func existingDir(p string) bool { st, err := os.Stat(p); return err == nil && st.IsDir() }

// Resolve the existing ancestor while allowing directories generated by earlier steps.
func resolveWorkdir(root, work string) (string, error) {
	if !inside(root, work) {
		return "", fmt.Errorf("directory escapes workspace")
	}
	ancestor := work
	for {
		_, err := os.Lstat(ancestor)
		if err == nil {
			resolved, err := filepath.EvalSymlinks(ancestor)
			if err != nil || !existingDir(resolved) || !inside(root, resolved) {
				return "", fmt.Errorf("directory ancestor is invalid or outside workspace")
			}
			rel, _ := filepath.Rel(ancestor, work)
			return filepath.Join(resolved, rel), nil
		}
		if !os.IsNotExist(err) || ancestor == root {
			return "", fmt.Errorf("cannot resolve directory %s: %w", ancestor, err)
		}
		ancestor = filepath.Dir(ancestor)
	}
}

// Find a repository root without invoking git (also works in source archives).
func workspace(source, explicit string) (string, error) {
	if explicit != "" {
		root, err := filepath.Abs(explicit)
		if err != nil {
			return "", err
		}
		root, err = filepath.EvalSymlinks(root)
		if err != nil || !existingDir(root) || !inside(root, source) {
			return "", fmt.Errorf("workspace-root must be a directory containing source")
		}
		return root, nil
	}
	for dir := source; ; dir = filepath.Dir(dir) {
		if _, err := os.Stat(filepath.Join(dir, ".git")); err == nil {
			return dir, nil
		}
		if filepath.Dir(dir) == dir {
			break
		}
	}
	return source, nil
}

func makePlan(c Config, opts CLI, buildID string) (Plan, error) {
	source, err := filepath.Abs(opts.Source)
	if err != nil {
		return Plan{}, err
	}
	source, err = filepath.EvalSymlinks(source)
	if err != nil || !existingDir(source) {
		return Plan{}, fmt.Errorf("source must be an existing local directory: %s", opts.Source)
	}
	root, err := workspace(source, opts.Workspace)
	if err != nil {
		return Plan{}, err
	}
	p := Plan{Source: source, Workspace: root}
	timeout := c.Timeout
	if opts.Timeout != "" {
		timeout = opts.Timeout
	}
	p.Timeout, err = duration(timeout, 10*time.Minute)
	if err != nil {
		return p, err
	}
	values := map[string]string{"PROJECT_ID": opts.Project, "PROJECT_NUMBER": "", "BUILD_ID": buildID, "LOCATION": opts.Region}
	for _, k := range []string{"TRIGGER_NAME", "COMMIT_SHA", "REVISION_ID", "SHORT_SHA", "REPO_NAME", "REPO_FULL_NAME", "BRANCH_NAME", "TAG_NAME", "REF_NAME", "TRIGGER_BUILD_CONFIG_PATH", "SERVICE_ACCOUNT_EMAIL", "SERVICE_ACCOUNT", "_HEAD_BRANCH", "_BASE_BRANCH", "_HEAD_REPO_URL", "_PR_NUMBER"} {
		values[k] = ""
	}
	for k, v := range c.Substitutions {
		if !userKey.MatchString(k) {
			return p, fmt.Errorf("invalid custom substitution %q", k)
		}
		values[k] = v
	}
	for k, v := range opts.Substitutions {
		if !userKey.MatchString(k) {
			if _, ok := values[k]; !ok || k == "PROJECT_ID" || k == "BUILD_ID" {
				return p, fmt.Errorf("invalid substitution override %q", k)
			}
		}
		values[k] = v
	}
	loose := c.Options.SubstitutionOption == "ALLOW_LOOSE"
	if c.Options.SubstitutionOption != "" && !loose && c.Options.SubstitutionOption != "MUST_MATCH" {
		return p, fmt.Errorf("unsupported substitutionOption")
	}
	sub := func(s string) string {
		if err != nil {
			return s
		}
		var out string
		out, err = substitute(s, values, loose)
		return out
	}
	ids := map[string]bool{}
	for i, st := range c.Steps {
		if st.Name == "" {
			return p, fmt.Errorf("step %d has no name", i)
		}
		if st.ID != "" && (ids[st.ID] || st.ID == "-") {
			return p, fmt.Errorf("duplicate or invalid step id %q", st.ID)
		}
		for _, dep := range st.WaitFor {
			if dep != "-" && !ids[dep] {
				return p, fmt.Errorf("step %d depends on unknown or later step %q", i, dep)
			}
		}
		if st.ID != "" {
			ids[st.ID] = true
		}
		if st.Script != "" && (st.Entrypoint != "" || len(st.Args) > 0) {
			return p, fmt.Errorf("step %d: script cannot be combined with args/entrypoint", i)
		}
		st.Name = sub(st.Name)
		st.Dir = sub(st.Dir)
		st.Entrypoint = sub(st.Entrypoint)
		for j := range st.Args {
			st.Args[j] = sub(st.Args[j])
		}
		// Cloud Build does not substitute the script field; use automapSubstitutions.
		env := map[string]string{}
		automap := c.Options.Automap
		if st.Automap != nil {
			automap = *st.Automap
		}
		if automap {
			for k, v := range values {
				env[k] = v
			}
		}
		for _, e := range append(append([]string{}, c.Options.Env...), st.Env...) {
			e = sub(e)
			k, v, ok := strings.Cut(e, "=")
			if !ok || k == "" {
				return p, fmt.Errorf("invalid env %q", e)
			}
			switch k {
			case "DOCKER_CONFIG", "DOCKER_HOST", "GCLOUD_LOCAL_NO_PUSH":
				return p, fmt.Errorf("reserved environment variable %s", k)
			}
			env[k] = v
		}
		var envList []string
		for k, v := range env {
			envList = append(envList, k+"="+v)
		}
		sort.Strings(envList)
		work := source
		if st.Dir != "" {
			clean := path.Clean(st.Dir)
			if path.IsAbs(clean) {
				if clean != "/workspace" && !strings.HasPrefix(clean, "/workspace/") {
					return p, fmt.Errorf("step %d: absolute dir must be under /workspace", i)
				}
				work = filepath.Join(root, strings.TrimPrefix(clean, "/workspace"))
			} else {
				work = filepath.Join(source, filepath.FromSlash(clean))
			}
		}
		resolved, e := resolveWorkdir(root, work)
		if e != nil {
			return p, fmt.Errorf("step %d: directory %q: %w", i, st.Dir, e)
		}
		rel, _ := filepath.Rel(root, resolved)
		stepTimeout, e := duration(st.Timeout, p.Timeout)
		if e != nil {
			return p, e
		}
		vols := append(append([]Volume{}, c.Options.Volumes...), st.Volumes...)
		paths := map[string]bool{}
		for _, v := range vols {
			if !regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9_.-]*$`).MatchString(v.Name) || !path.IsAbs(v.Path) || path.Clean(v.Path) != v.Path {
				return p, fmt.Errorf("invalid volume %+v", v)
			}
			if paths[v.Path] || v.Path == "/" || v.Path == "/workspace" || strings.HasPrefix(v.Path, "/workspace/") || v.Path == "/gcloud-local" || strings.HasPrefix(v.Path, "/gcloud-local/") || v.Path == "/root" || strings.HasPrefix(v.Path, "/root/") || v.Path == "/var/run" || v.Path == "/var/run/docker.sock" {
				return p, fmt.Errorf("conflicting volume path %s", v.Path)
			}
			paths[v.Path] = true
		}
		st.Volumes = vols
		p.Steps = append(p.Steps, StepPlan{Step: st, Image: st.Name, Workdir: path.Join("/workspace", filepath.ToSlash(rel)), Env: envList, Timeout: stepTimeout})
	}
	for _, im := range c.Images {
		p.Images = append(p.Images, sub(im))
	}
	if err != nil {
		return p, err
	}
	return p, nil
}
